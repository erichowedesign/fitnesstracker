struct ExerciseTipSet: Hashable {
    let source: String?
    let tips: [String]
}

enum ExerciseTips {
    static func set(for name: String) -> ExerciseTipSet {
        if let tips = pasted[name] {
            return ExerciseTipSet(source: nil, tips: tips)
        }
        return sourced[name] ?? ExerciseTipSet(source: nil, tips: [])
    }

    static func set(for name: String, slug: String) -> ExerciseTipSet {
        let direct = set(for: name)
        if !direct.tips.isEmpty { return direct }
        guard let workout = LibraryCatalog.workout(slug: slug) else { return direct }
        return set(for: workout.name)
    }

